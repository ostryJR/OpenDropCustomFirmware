#!/usr/bin/env python3
"""Convert a .wav to an OpenDropAudio sound header, or generate the default sounds.

OpenDropAudio plays raw unsigned 8-bit mono PCM at 16 kHz (OpenDropAudio.begin(16000)).
Sound slots:  sound1 = menu,  sound2 = startup,  sound3 = drop-move tick.

Usage:
  python3 tools/wav2sound.py in.wav sound1 Libraries/OpenDropAudio/src/Sound1.h [--gain 0.6]
  python3 tools/wav2sound.py --generate [--preview DIR]

Standard library only (no audioop, which is gone since Python 3.13).
"""
import argparse
import math
import os
import struct
import sys
import wave

RATE = 16000
HERE = os.path.dirname(os.path.abspath(__file__))
SRC_DIR = os.path.join(HERE, "..", "Libraries", "OpenDropAudio", "src")


# ---------- reading / processing ----------

def read_wav(path):
    """Return (mono float samples in -1..1, sample rate)."""
    with wave.open(path, "rb") as w:
        ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    total = n * ch
    if width == 1:
        vals = [(b - 128) / 128.0 for b in raw]
    elif width == 2:
        vals = [v / 32768.0 for v in struct.unpack("<%dh" % total, raw)]
    elif width == 3:
        vals = []
        for i in range(0, len(raw), 3):
            v = int.from_bytes(raw[i:i + 3], "little", signed=True)
            vals.append(v / 8388608.0)
    elif width == 4:
        vals = [v / 2147483648.0 for v in struct.unpack("<%di" % total, raw)]
    else:
        sys.exit("Unsupported sample width: %d bytes" % width)
    mono = [sum(vals[i:i + ch]) / ch for i in range(0, len(vals), ch)]
    return mono, rate


def resample(x, src_rate, dst_rate=RATE):
    if src_rate == dst_rate or not x:
        return list(x)
    n_out = int(len(x) * dst_rate / src_rate)
    step = src_rate / dst_rate
    out = []
    for i in range(n_out):
        p = i * step
        j = int(p)
        f = p - j
        a = x[j]
        b = x[j + 1] if j + 1 < len(x) else a
        out.append(a + (b - a) * f)
    return out


def trim(x, thresh=0.02):
    peak = max((abs(v) for v in x), default=0)
    if peak == 0:
        return x
    lim = peak * thresh
    start = next(i for i, v in enumerate(x) if abs(v) > lim)
    end = len(x) - next(i for i, v in enumerate(reversed(x)) if abs(v) > lim)
    return x[start:end]


def finish(x, gain, fade_ms=5):
    """Normalise to peak, apply gain and short fades, convert to unsigned 8-bit."""
    peak = max((abs(v) for v in x), default=0) or 1.0
    x = [v / peak * gain for v in x]
    nf = min(int(RATE * fade_ms / 1000), len(x) // 2)
    for i in range(nf):
        k = i / nf
        x[i] *= k
        x[-1 - i] *= k
    return bytes(max(0, min(255, int(round(128 + 127 * v)))) for v in x)


# ---------- output ----------

def write_header(data, name, path):
    lines = ["#include <avr/pgmspace.h>",
             "// %s: %d samples, unsigned 8-bit mono @ %d Hz (%.0f ms). Generated by tools/wav2sound.py"
             % (name, len(data), RATE, 1000 * len(data) / RATE),
             " const uint8_t %s[%d] PROGMEM = {" % (name, len(data))]
    for i in range(0, len(data), 12):
        chunk = ", ".join("0x%02x" % b for b in data[i:i + 12])
        lines.append("  " + chunk + ("," if i + 12 < len(data) else ""))
    lines.append("};")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s  (%d bytes, %.0f ms)" % (path, len(data), 1000 * len(data) / RATE))
    if len(data) > 1.5 * RATE:
        print("  warning: longer than 1.5 s - uses a lot of flash", file=sys.stderr)


def write_preview(data, path):
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(1)
        w.setframerate(RATE)
        w.writeframes(data)
    print("preview  %s" % path)


# ---------- synthesis ----------

def tone(buf, freq, start, tau, attack=0.005, harm=0.2, amp=1.0):
    """Add a decaying sine (+ a little 2nd harmonic) into buf starting at `start` seconds."""
    s0 = int(start * RATE)
    for i in range(s0, len(buf)):
        t = (i - s0) / RATE
        env = (t / attack if t < attack else math.exp(-(t - attack) / tau)) * amp
        if env < 1e-4 and t > attack:
            break
        ph = 2 * math.pi * freq * t
        buf[i] += env * (math.sin(ph) + harm * math.sin(2 * ph))


def gen_startup():
    buf = [0.0] * int(0.6 * RATE)
    tone(buf, 1046.5, 0.00, tau=0.10)            # C6
    tone(buf, 1318.5, 0.09, tau=0.10)            # E6
    tone(buf, 1568.0, 0.18, tau=0.16, amp=1.1)   # G6, rings a bit longer
    return finish(buf, gain=0.5, fade_ms=20)


def gen_menu():
    buf = [0.0] * int(0.09 * RATE)
    tone(buf, 784.0, 0.000, tau=0.018, attack=0.003)    # G5
    tone(buf, 1046.5, 0.035, tau=0.022, attack=0.003)   # C6
    return finish(buf, gain=0.45, fade_ms=5)


# ---------- main ----------

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("wav", nargs="?")
    ap.add_argument("name", nargs="?", help="array name, e.g. sound1")
    ap.add_argument("out", nargs="?", help="output .h path")
    ap.add_argument("--gain", type=float, default=0.6, help="peak level 0..1 (default 0.6)")
    ap.add_argument("--generate", action="store_true", help="write the default synthesised Sound1.h / Sound2.h")
    ap.add_argument("--preview", metavar="DIR", help="also write .wav previews of what the device will play")
    a = ap.parse_args()

    if a.generate:
        for name, data in (("sound1", gen_menu()), ("sound2", gen_startup())):
            write_header(data, name, os.path.join(SRC_DIR, name.capitalize() + ".h"))
            if a.preview:
                write_preview(data, os.path.join(a.preview, name + ".wav"))
        return

    if not (a.wav and a.name and a.out):
        ap.error("need: in.wav name out.h  (or --generate)")
    x, rate = read_wav(a.wav)
    data = finish(trim(resample(x, rate)), a.gain)
    write_header(data, a.name, a.out)
    if a.preview:
        write_preview(data, os.path.join(a.preview, a.name + ".wav"))


if __name__ == "__main__":
    main()
